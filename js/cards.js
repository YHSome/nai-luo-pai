/* ------------------------- 组装整副牌 ------------------------- */
function buildDeck() {
  const deck = [];

  MAJOR.forEach((c, i) => {
    deck.push({
      id: 'major-' + i,
      name: c.name,
      en: c.en,
      arcana: 'major',
      suit: 'major',
      rank: 0,
      numeral: String(i),
      element: c.element,
      up: c.up,
      rev: c.rev
    });
  });

  Object.keys(MINOR_RAW).forEach(suit => {
    MINOR_RAW[suit].forEach((row, i) => {
      const rank = i + 1;
      const fullName = row[0];
      deck.push({
        id: suit + '-' + rank,
        name: rank <= 10 ? (SUITS[suit].name + RANK_NAME[rank]) : fullName,
        en: row[1],
        arcana: 'minor',
        suit,
        rank,
        numeral: RANK_NUM[rank],
        element: SUITS[suit].element,
        up: { kw: row[2], text: row[4] },
        rev: { kw: row[3], text: row[5] }
      });
    });
  });

  return deck;
}

const DECK = buildDeck();
